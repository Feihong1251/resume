#include <iostream>

int main() {
    // หลักการเลื่อนจอ "เลื่อนลง" (Scroll Down)
    // คือการลากนิ้วจาก "ข้างล่าง" ขึ้นไป "ข้างบน"
    
    int startX = 500;   // จุดแนวนอนกลางจอ
    int startY = 800;   // เริ่มที่ด้านล่าง
    int endX = 500;     // แนวนอนเท่าเดิม (ลากตรงๆ)
    int endY = 200;     // ไปจบที่ด้านบน
    
    // ส่งออกไป 4 ค่า คั่นด้วยเว้นวรรค
    std::cout << startX << " " << startY << " " << endX << " " << endY;
    
    return 0;
}